/*
 * Contract:
 * - A dependent generator that first chooses a size and then builds a vector of
 *   exactly that size must generate and shrink only values that satisfy
 *   vector.size() == generated_size.
 * - Replaying the same seed through that dependent generator must produce the
 *   same sequence of generated roots.
 * - A filtered flatMap generator must not expose shrink candidates that violate
 *   the filter predicate.
 *
 * Scope:
 * This file covers dependent-generator replay and shrink-domain preservation.
 * It does not cover all flatMap edge cases, distribution quality, or exact
 * shrink-tree shape.
 *
 * Helpers:
 * - VectorWithGeneratedSize is pair<int, vector<int>>. The int is the outer
 *   generated size; the vector is generated by the inner generator with
 *   setSize(size, size).
 * - dependentSizeVectorGen() creates values like {3, [a, b, c]}; both roots and
 *   shrink candidates are required to keep the vector length equal to 3.
 * - collectShrinkViolations() walks a bounded breadth-first view of a shrink
 *   tree and returns every visited value that fails the supplied invariant.
 */

#include "proptest/proptest.hpp"
#include "proptest/test/gtest.hpp"
#include "proptest/test/test_profiles.hpp"

using namespace proptest;
using namespace proptest::testprofile;

namespace {

using VectorWithGeneratedSize = pair<int, vector<int>>;

Generator<VectorWithGeneratedSize> dependentSizeVectorGen()
{
    return gen::interval(0, 5).flatMap<VectorWithGeneratedSize>([](const int& size) {
        auto values = gen::vector<int>(gen::interval(-10, 10));
        values.setSize(size, size);
        return values.map<VectorWithGeneratedSize>([size](vector<int>& items) {
            return util::make_pair(size, items);
        });
    });
}

bool isValidDependentSizeVector(const VectorWithGeneratedSize& value)
{
    return value.first >= 0 && value.first <= 5 && value.second.size() == static_cast<size_t>(value.first);
}

int sum(const vector<int>& values)
{
    int total = 0;
    for (int value : values) {
        total += value;
    }
    return total;
}

template <typename T, typename Predicate>
vector<T> collectShrinkViolations(Shrinkable<T> root, Predicate predicate)
{
    vector<T> violations;
    vector<Shrinkable<T>> pending{root};
    size_t visited = 0;

    for (size_t index = 0; index < pending.size() && visited < kShrinkTraversalLimit; ++index, ++visited) {
        const auto current = pending[index];
        if (!predicate(current.getRef())) {
            violations.push_back(current.getRef());
        }

        auto shrinks = current.getShrinks();
        for (auto itr = shrinks.template iterator<typename Shrinkable<T>::StreamElementType>();
             itr.hasNext() && pending.size() < kShrinkTraversalLimit;) {
            pending.push_back(itr.next());
        }
    }

    return violations;
}

vector<VectorWithGeneratedSize> collectDependentSizeVectorTrace(uint64_t seed, size_t sampleCount)
{
    auto generator = dependentSizeVectorGen();
    Random rand(seed);
    vector<VectorWithGeneratedSize> trace;
    for (size_t i = 0; i < sampleCount; ++i) {
        trace.push_back(generator(rand).getRef());
    }
    return trace;
}

}  // namespace

TEST(DependentGeneratorContracts, flatmap_replays_same_dependent_trace_for_same_seed)
{
    const auto first = collectDependentSizeVectorTrace(kCompatibilitySeed, kShortSamples);
    const auto second = collectDependentSizeVectorTrace(kCompatibilitySeed, kShortSamples);

    EXPECT_EQ(first, second);
    for (const auto& value : first) {
        EXPECT_TRUE(isValidDependentSizeVector(value));
    }
}

TEST(DependentGeneratorContracts, flatmap_shrinks_preserve_dependent_size_contract)
{
    auto generator = dependentSizeVectorGen();
    Random rand(kCompatibilitySeed);

    for (size_t i = 0; i < kFocusedSamples; ++i) {
        const auto root = generator(rand);
        const auto violations = collectShrinkViolations(root, isValidDependentSizeVector);
        EXPECT_TRUE(violations.empty()) << "flatMap shrink tree must preserve size-dependent vector contract";
    }
}

TEST(DependentGeneratorContracts, filtered_flatmap_shrinks_preserve_filter_contract)
{
    auto generator = gen::interval(1, 10)
        .flatMap<vector<int>>([](const int& size) {
            auto values = gen::vector<int>(gen::interval(1, 10));
            values.setSize(size, size);
            return values;
        })
        .filter([](const vector<int>& values) {
            return sum(values) > 10;
        });

    Random rand(kCompatibilitySeed);
    for (size_t i = 0; i < kFocusedSamples; ++i) {
        const auto root = generator(rand);
        ASSERT_GT(sum(root.getRef()), 10);

        const auto violations = collectShrinkViolations(root, [](const vector<int>& values) {
            return sum(values) > 10;
        });
        EXPECT_TRUE(violations.empty()) << "filter+flatMap shrink tree must preserve the accepted domain";
    }
}
